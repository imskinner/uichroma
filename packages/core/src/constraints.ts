// AI constraint-pack generators. Turn a generated palette into the rules files that codegen
// agents ingest so they produce *this* brand's UI instead of the generic shadcn/Inter default.
// Three flavors share one body: a generic AGENTS.md, a Claude Code skill, and a Cursor rule.
// Pure and browser-safe (depends only on token role metadata, never the generation engine).

import { TOKEN_ROLES, type TokenColorsInput } from "./tokens";
import type { ColorRole } from "./types";

type Role = ColorRole | "neutral";

export interface ConstraintPackInput {
  /** The 8 role colors (role -> { hex, h, s, description?, tones? }). */
  colors: TokenColorsInput;
  /** The original prompt the palette was generated from, if known. */
  vibe?: string;
  /** Explicit brand name; defaults to a label derived from the vibe. */
  name?: string;
  /** Permalink/slug of the saved palette, used for a provenance backlink. */
  permalink?: string;
}

/** Semantic usage guidance per role — the rules the agent must follow, independent of vibe. */
const ROLE_USAGE: Record<string, string> = {
  primary:
    "Dominant brand color. App chrome, primary buttons, active nav, links, focus rings.",
  secondary:
    "Supporting brand color. Secondary surfaces, alternate sections, less prominent UI.",
  accent:
    "The single most important call-to-action / interactive highlight on a view. Never use for body text or large background fills.",
  warning: "Cautionary, non-blocking states. Warning banners, confirmation prompts.",
  danger:
    "Destructive or error states ONLY. Delete actions, validation errors, error toasts. Never decorative.",
  success: "Positive confirmation. Success toasts, completed states, valid input.",
  info: "Neutral informational. Info banners, tips, secondary status.",
  neutral:
    "Text, borders, backgrounds, and surfaces. Use its tonal scale for typography and lines; avoid pure #000.",
};

const HARD_RULES: string[] = [
  "Use the design tokens (CSS variables `--color-<role>`, Tailwind color classes, or the DTCG token names) — never hardcode hex values in components.",
  "`accent` is for the primary call-to-action only. At most one accent action per view; never use accent for body text or large background fills.",
  "`danger` is exclusively for destructive/error states. `success` / `warning` / `info` are status colors — do not repurpose any of them as brand or decorative colors.",
  "Use the tonal scale (`-10` darkest … `-95` lightest) for hover/active/disabled states, borders, and surfaces. Do not invent new shades.",
  "Body text, borders, and surfaces use `neutral` and its tones. Avoid pure black (#000) and pure white for large blocks of text.",
  "Keep foreground/background pairs accessible (target WCAG AA): put text on a sufficiently light or dark tone of the role, or on `neutral`.",
];

function slugify(s: string): string {
  const out = s
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 40)
    .replace(/-+$/g, "");
  return out || "brand";
}

function presentRoles(colors: TokenColorsInput): Role[] {
  return TOKEN_ROLES.filter((r) => colors[r]);
}

function titleCase(role: string): string {
  return role.charAt(0).toUpperCase() + role.slice(1);
}

/** The shared markdown body: token table, hard rules, and per-role brand intent. */
function buildBody(input: ConstraintPackInput): string {
  const { colors, vibe, permalink } = input;
  const roles = presentRoles(colors);

  const lines: string[] = [];

  if (vibe) {
    lines.push(`Generated by UI Chroma from the prompt: _"${vibe}"_.`);
  } else {
    lines.push("Generated by UI Chroma.");
  }
  lines.push("");
  lines.push(
    "When generating or editing any UI in this project, use these tokens and rules so the result matches the brand instead of defaulting to a generic look.",
  );
  lines.push("");

  // Token table
  lines.push("## Tokens");
  lines.push("");
  lines.push("| Role | CSS variable | Hex | What it's for |");
  lines.push("| --- | --- | --- | --- |");
  for (const role of roles) {
    const c = colors[role]!;
    lines.push(
      `| ${titleCase(role)} | \`--color-${role}\` | \`${c.hex}\` | ${ROLE_USAGE[role]} |`,
    );
  }
  lines.push("");
  lines.push(
    "Each role also has a 10-step tonal scale (`--color-<role>-10` … `--color-<role>-95`, dark → light) for states and surfaces. The full machine-readable token set is the W3C DTCG file `tokens.dtcg.json` — reference it rather than copying hex values.",
  );
  lines.push("");

  // Hard rules
  lines.push("## Rules");
  lines.push("");
  HARD_RULES.forEach((rule, i) => lines.push(`${i + 1}. ${rule}`));
  lines.push("");

  // Brand intent (the model's rationale, if present)
  const withDesc = roles.filter((r) => colors[r]!.description);
  if (withDesc.length) {
    lines.push("## Brand intent");
    lines.push("");
    for (const role of withDesc) {
      const c = colors[role]!;
      lines.push(`- **${titleCase(role)}** (\`${c.hex}\`): ${c.description}`);
    }
    lines.push("");
  }

  if (permalink) {
    lines.push(`> Source palette: UI Chroma permalink \`${permalink}\`.`);
    lines.push("");
  }

  return lines.join("\n").trimEnd() + "\n";
}

function brandTitle(input: ConstraintPackInput): string {
  if (input.name?.trim()) return input.name.trim();
  if (input.vibe?.trim()) {
    return input.vibe
      .trim()
      .split(/\s+/)
      .slice(0, 6)
      .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
      .join(" ");
  }
  return "Brand";
}

/** Generic `AGENTS.md` — read by most coding agents. */
export function generateAgentsMd(input: ConstraintPackInput): string {
  return `# ${brandTitle(input)} Design Tokens\n\n${buildBody(input)}`;
}

/** Claude Code skill (`SKILL.md`) — pairs with the bundled `tokens.dtcg.json`. */
export function generateClaudeSkill(input: ConstraintPackInput): string {
  const slug = slugify(input.name || input.vibe || "brand");
  const description = `Apply the ${brandTitle(input)} design tokens whenever generating or editing UI in this project (components, pages, styles).`;
  const frontmatter = [
    "---",
    `name: ${slug}-theme`,
    `description: ${description}`,
    "---",
    "",
  ].join("\n");
  return `${frontmatter}# ${brandTitle(input)} Theme\n\n${buildBody(input)}`;
}

/** Cursor project rule (`.cursor/rules/<slug>-theme.mdc`). */
export function generateCursorRules(input: ConstraintPackInput): string {
  const frontmatter = [
    "---",
    `description: ${brandTitle(input)} design tokens — use these for all UI in this project`,
    "globs: **/*.{tsx,jsx,ts,js,css,scss,sass,less,vue,svelte,astro,html}",
    "alwaysApply: true",
    "---",
    "",
  ].join("\n");
  return `${frontmatter}# ${brandTitle(input)} Design Tokens\n\n${buildBody(input)}`;
}
